function result = simulate_half_car(sys, time, road_x, road_z, speed, vehicle)
%SIMULATE_HALF_CAR Linear half-car solution and engineering outputs.
% No figure, playback-speed, or video inputs: rendering cannot change results.
% State order: [z theta zu_front zu_rear dz dtheta dzu_front dzu_rear].
% Positive z is up; positive theta lowers the front body attachment.
% Vehicle fields use a consistent one-side or axle-equivalent convention.

validateattributes(time, {'numeric'}, {'real','finite','vector','nonempty'});
validateattributes(road_x, {'numeric'}, {'real','finite','vector','nonempty'});
validateattributes(road_z, {'numeric'}, {'real','finite','vector','nonempty'});
validateattributes(speed, {'numeric'}, {'real','finite','scalar','positive'});
time = time(:); road_x = road_x(:); road_z = road_z(:);
assert(numel(time) >= 2 && time(1) == 0 && all(diff(time) > 0), ...
    'HalfCar:TimeGrid', 'Time must start at zero and strictly increase.');
step = diff(time);
assert(max(abs(step-step(1))) <= 1e-9*max(1,step(1)), ...
    'HalfCar:TimeGrid', 'lsim requires an evenly spaced time grid.');
assert(numel(road_x) == numel(road_z) && numel(road_x) >= 2 && ...
    all(diff(road_x) > 0), 'HalfCar:RoadGrid', ...
    'Road coordinates must strictly increase and match road heights.');
fields = {'m','m1','m2','a1','a2','kt1','kt2'};
for index = 1:numel(fields)
    validateattributes(vehicle.(fields{index}), {'numeric'}, ...
        {'real','finite','scalar','positive'});
end
assert(size(sys.A,1) == 8 && size(sys.B,2) == 2, ...
    'HalfCar:StateSpace', 'Expected eight states and two road inputs.');
front_position = speed*time + vehicle.a1 + vehicle.a2;
rear_position = speed*time;
position_tolerance = 1e-10*max(1,max(abs(road_x)));
assert(rear_position(1) >= road_x(1)-position_tolerance && ...
    front_position(end) <= road_x(end)+position_tolerance, ...
    'HalfCar:RoadCoverage', 'Road must cover both wheels for the entire run.');
% Clamp roundoff at endpoints only, never extrapolate missing road geometry.
front_position = min(max(front_position,road_x(1)),road_x(end));
rear_position = min(max(rear_position,road_x(1)),road_x(end));
road_inputs = [interp1(road_x,road_z,front_position,'linear'), ...
    interp1(road_x,road_z,rear_position,'linear')];
assert(all(isfinite(road_inputs(:))), 'HalfCar:RoadInput', ...
    'Road input contains nonfinite values.');
[~,~,states] = lsim(sys,road_inputs,time,zeros(8,1),'foh');
assert(all(isfinite(states(:))), 'HalfCar:Response', ...
    'Simulation produced nonfinite states.');
% State-space equations give acceleration directly, without numerical diff.
derivative = (sys.A*states.' + sys.B*road_inputs.').';
body_acceleration = derivative(:,5);
suspension_travel = [states(:,1)-vehicle.a1*states(:,2)-states(:,3), ...
    states(:,1)+vehicle.a2*states(:,2)-states(:,4)];
g = 9.81;
wheelbase = vehicle.a1 + vehicle.a2;
static_loads = g*[vehicle.m*vehicle.a2/wheelbase + vehicle.m1, ...
    vehicle.m*vehicle.a1/wheelbase + vehicle.m2];
% Includes static weight; negative total load violates continuous contact.
tire_loads = repmat(static_loads,numel(time),1) + ...
    (road_inputs-states(:,3:4))*diag([vehicle.kt1 vehicle.kt2]);
result = struct('time',time,'states',states,'road_inputs',road_inputs, ...
    'body_acceleration',body_acceleration,'suspension_travel',suspension_travel, ...
    'static_tire_loads',static_loads,'tire_loads',tire_loads);
result.metric_names = {'Peak absolute body displacement'; 'Peak absolute pitch'; ...
    'Peak absolute body acceleration'; 'Peak absolute front travel'; ...
    'Peak absolute rear travel'; 'Minimum front tire load'; ...
    'Minimum rear tire load'; 'RMS body acceleration (whole run)'};
result.metric_units = {'m';'rad';'m/s^2';'m';'m';'N';'N';'m/s^2'};
result.metric_values = [max(abs(states(:,1))); max(abs(states(:,2))); ...
    max(abs(body_acceleration)); max(abs(suspension_travel(:,1))); ...
    max(abs(suspension_travel(:,2))); min(tire_loads(:,1)); ...
    min(tire_loads(:,2)); sqrt(trapz(time,body_acceleration.^2)/(time(end)-time(1)))];
end
